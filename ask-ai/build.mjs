// One self-contained script, no framework required on the host page.
// Preact rather than React: the same source, a tenth of the bytes, and this
// file ships to pages that did not ask for a UI runtime.
import {readFileSync} from 'node:fs';
import {join} from 'node:path';
import {build} from 'esbuild';

const dev = process.argv.includes('--dev');

// The site's accent, read at build time so the widget follows docs.json:
// colors.primary on a light ground, colors.light on a dark one.
const {colors} = JSON.parse(
  readFileSync(join(import.meta.dirname, '../docs.json'), 'utf8'),
);

await build({
  entryPoints: [join(import.meta.dirname, 'src/index.tsx')],
  bundle: true,
  format: 'iife',
  target: ['es2022'],
  minify: !dev,
  sourcemap: dev,
  jsx: 'automatic',
  jsxImportSource: 'preact',
  // The orb's shader library is written against React. Preact's compat layer
  // stands in for it, so the widget ships one small runtime rather than two.
  alias: {
    react: 'preact/compat',
    'react-dom': 'preact/compat',
    'react/jsx-runtime': 'preact/jsx-runtime',
  },
  loader: {'.css': 'text'},
  define: {
    __EKA_ACCENT__: JSON.stringify(colors.primary),
    __EKA_ACCENT_DARK__: JSON.stringify(colors.light ?? colors.primary),
  },
  banner: {js: '// Generated by ask-ai/build.mjs. Do not edit.'},
  // Mintlify serves any .js at the repo root on every page.
  outfile: join(import.meta.dirname, '../ask-ai.js'),
});
