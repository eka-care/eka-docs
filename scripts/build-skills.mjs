export const skillDir = (slug) => `plugins/eka-${slug}/skills/eka-${slug}`;
export const installLines = (slug) => [`/plugin marketplace add ${REPO}`, `/plugin install eka-${slug}@eka-docs`];
export const rawSkillUrl = (slug) => `${RAW}/${skillDir(slug)}/SKILL.md`;

// ---------- reading ----------

function walkPages(n, out = []) {
  if (typeof n === 'string') out.push(n);
  else if (Array.isArray(n)) n.forEach((x) => walkPages(x, out));
  else if (n && typeof n === 'object') {
    if (n.root) out.push(n.root);
    for (const k of ['pages', 'groups', 'tabs', 'menu']) if (n[k]) walkPages(n[k], out);
  }
  return out;
}

function findItem(docs, name) {
  for (const fam of docs.navigation.products) for (const it of fam.menu) if (it.item === name) return it;
  return null;
}

export function apiPagesOf(docs, name) {
  const tab = (findItem(docs, name)?.tabs ?? []).find((t) => t.tab === API_TAB);
  return tab ? walkPages(tab.pages) : [];
}

function docsHomeOf(docs, name) {
  const tab = (findItem(docs, name)?.tabs ?? []).find((t) => t.tab === 'Documentation');
  // The product's own overview: its Build with AI pages describe the tools, not the product.
  return tab ? walkPages(tab.pages).find((p) => !p.includes('/build-with-ai')) ?? null : null;
}

function readPage(root, page) {
  const file = path.join(root, page + '.mdx');
  if (!fs.existsSync(file)) return null;
  const { data, content } = matter(fs.readFileSync(file, 'utf8'));
  return { heading: content.match(/^#\s+(.+)$/m)?.[1], ...data };
}

export function loadSpecs(root) {
  const files = [];
  const walk = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      if (e.isDirectory()) { if (!SKIP_DIRS.has(e.name)) walk(path.join(dir, e.name)); }
      else if (/\.(ya?ml|json)$/.test(e.name)) files.push(path.relative(root, path.join(dir, e.name)).split(path.sep).join('/'));
    }
  };
  walk(root);
  const specs = new Map();
  for (const f of files.sort()) {
    let doc;
    try { doc = YAML.parse(fs.readFileSync(path.join(root, f), 'utf8')); } catch { continue; }
    if (doc && typeof doc === 'object' && (doc.openapi || doc.swagger) && doc.paths) specs.set(f, doc);
  }
  return specs;
}

const hasOp = (spec, method, p) => Boolean(spec?.paths?.[p]?.[method.toLowerCase()]);

// The operation a page documents. A bare `METHOD /path` resolves the way Mintlify does: to the alphabetically first
// spec that has it. `ambiguous` says another spec has it too, so the page may not show the operation its author meant.
export function operationOf(frontmatter, specs) {
  const parsed = frontmatter?.openapi ? normalizeOp(frontmatter.openapi) : null;
  if (!parsed) return null;
  const [method, ...rest] = parsed.op.split(' ');
  const p = rest.join(' ');
  if (parsed.spec) return hasOp(specs.get(parsed.spec), method, p) ? { spec: parsed.spec, method, path: p, ambiguous: false } : null;
  const found = [...specs.keys()].sort().filter((f) => hasOp(specs.get(f), method, p));
  return found.length ? { spec: found[0], method, path: p, ambiguous: found.length > 1 } : null;
}

// ---------- writing ----------

// "Eka EMR" is already branded; "Scribe" becomes "Eka Scribe".
const branded = (name) => (name.startsWith('Eka ') ? name : `Eka ${name}`);
const cell = (s) => String(s ?? '').replace(/\s*\u2014\s*/g, ', ').replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
const firstSentence = (s) => cell(s).split(/(?<=\.)\s/)[0];

function resolve(spec, x) {
  if (!x?.$ref?.startsWith('#/')) return x;
  return x.$ref.slice(2).split('/').reduce((o, k) => o?.[k], spec) ?? x;
}

function opDoc(specs, o) {
  return specs.get(o.spec).paths[o.path][o.method.toLowerCase()];
}

function headerParams(spec, pathItem, op) {
  return [...(pathItem.parameters ?? []), ...(op.parameters ?? [])].map((p) => resolve(spec, p))
    .filter((p) => p?.in === 'header');
}

function schemeLine(name, s) {
  if (s.type === 'http') return `- \`${name}\`: HTTP ${s.scheme}. Send \`Authorization: ${s.scheme === 'bearer' ? 'Bearer <token>' : '<credentials>'}\`.`;
  if (s.type === 'apiKey') return `- \`${name}\`: API key in the \`${s.name}\` ${s.in}.`;
  if (s.type === 'oauth2') return `- \`${name}\`: OAuth 2.0.`;
  return `- \`${name}\`: ${s.type}.`;
}

function example(spec, op) {
  const body = resolve(spec, op.requestBody);
  const json = body?.content?.['application/json'];
  if (!json) return undefined;
  if (json.example !== undefined) return json.example;
  const first = Object.values(json.examples ?? {})[0];
  if (first) return resolve(spec, first).value;
  return resolve(spec, json.schema)?.example;
}

function curl(specs, o) {
  const spec = specs.get(o.spec);
  const pathItem = spec.paths[o.path];
  const op = pathItem[o.method.toLowerCase()];
  const host = spec.servers?.[0]?.url ?? '<host>';
  const lines = [`curl -X ${o.method} '${host}${o.path}'`];
  const schemes = spec.components?.securitySchemes ?? {};
  const used = (op.security ?? spec.security ?? []).flatMap((r) => Object.keys(r));
  for (const name of used.length ? used : Object.keys(schemes)) {
    const s = schemes[name];
    if (s?.type === 'http' && s.scheme === 'bearer') lines.push(`  -H 'Authorization: Bearer <token>'`);
    else if (s?.type === 'apiKey' && s.in === 'header') lines.push(`  -H '${s.name}: <${s.name}>'`);
  }
  for (const h of headerParams(spec, pathItem, op).filter((h) => h.required)) lines.push(`  -H '${h.name}: <${h.name}>'`);
  const ex = example(spec, op);
  if (ex !== undefined) {
    lines.push(`  -H 'Content-Type: application/json'`);
    lines.push(`  -d '${JSON.stringify(ex, null, 2).replace(/'/g, "'\\''")}'`);
  }
  return lines.join(' \\\n');
}

export function integrateMd(product, operations, specs, guides) {
  const used = [...new Set(operations.map((o) => o.spec))];
  const out = [`<!-- ${GENERATED} from docs.json and the specs it points at. Do not edit by hand. -->`, '',
    `# Integrate ${product.item}`, '',
    'The calls themselves: where they live, what they need in their headers, every operation, and one request written out in full.', ''];

  // Hosts once per URL, with the first description any spec gives it.
  const hosts = new Map();
  for (const f of used) for (const sv of specs.get(f).servers ?? []) {
    if (!hosts.has(sv.url)) hosts.set(sv.url, `- \`${sv.url}\`${sv.description ? ' ' + cell(sv.description) : ''}`);
  }
  out.push('## Hosts', '', ...(hosts.size ? hosts.values() : ['The specs name no host. Use the one on the operation\'s page.']), '');

  // Only the schemes the listed operations ask for (their own security, else their spec's default).
  // When two specs give one scheme name different meanings, each line says whose operations it is for.
  const seen = new Map(); // line -> specs using it
  for (const o of operations) {
    const spec = specs.get(o.spec);
    const schemes = spec.components?.securitySchemes ?? {};
    const reqs = opDoc(specs, o).security ?? spec.security;
    const names = reqs ? reqs.flatMap((r) => Object.keys(r)) : Object.keys(schemes);
    for (const name of names) {
      if (!schemes[name]) continue;
      const line = schemeLine(name, schemes[name]);
      if (!seen.has(line)) seen.set(line, { name, specs: new Set() });
      seen.get(line).specs.add(o.spec);
    }
  }
  const clash = (name) => [...seen.values()].filter((v) => v.name === name).length > 1;
  const auth = [...seen].map(([line, v]) => (clash(v.name) ? `${line} For operations in ${[...v.specs].sort().map((f) => `\`${f}\``).join(', ')}.` : line));
  const headers = new Set();
  for (const o of operations) {
    const spec = specs.get(o.spec);
    for (const h of headerParams(spec, spec.paths[o.path], opDoc(specs, o))) if (h.required) headers.add(h.name);
  }
  out.push('## Auth and headers', '', `Get a token first: [Authentication](${SITE}/api-sdk/auth/getting-started).`, '');
  if (auth.length) out.push(...auth, '');
  if (headers.size) out.push('Headers that some operations require:', '', ...[...headers].sort().map((h) => `- \`${h}\``), '');

  if (guides.length) {
    out.push('## Read first', '', ...guides.map((g) => `- [${cell(g.title)}](${SITE}/${g.page})`), '');
  }

  out.push('## Endpoints', '', `${operations.length} ${operations.length === 1 ? 'operation' : 'operations'}, grouped by tag.`, '');
  const byTag = new Map();
  for (const o of operations) {
    const tag = opDoc(specs, o).tags?.[0] ?? 'Other';
    if (!byTag.has(tag)) byTag.set(tag, []);
    byTag.get(tag).push(o);
  }
  for (const [tag, ops] of byTag) {
    out.push(`### ${cell(tag)}`, '', '| Method | Path | What it does |', '| --- | --- | --- |');
    const sorted = [...ops].sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : a.method < b.method ? -1 : a.method > b.method ? 1 : 0));
    for (const o of sorted) {
      const op = opDoc(specs, o);
      out.push(`| \`${o.method}\` | [\`${o.path}\`](${SITE}/${o.page}) | ${firstSentence(op.summary || op.description || o.title || '')} |`);
    }
    out.push('');
  }

  const sample = operations.find((o) => example(specs.get(o.spec), opDoc(specs, o)) !== undefined) ?? operations[0];
  if (sample) {
    out.push('## One request in full', '', `${sample.method} ${sample.path}, from [its page](${SITE}/${sample.page}).`, '',
      '```bash', curl(specs, sample), '```', '');
  }
  return out.join('\n');
}

const JOBS = {
  integrate: '**Integrate.** Hosts, auth and headers, every operation with a link to its page, and one request written out in full.',
};

export function skillMd(product, overview, jobs) {
  const desc = cell(overview.description);
  return [
    '---',
    `name: eka-${product.slug}`,
    `description: Use when building against ${branded(product.item)}${desc ? ': ' + desc.replace(/\.$/, '') : ''}. Carries the hosts, auth and headers, and every ${product.item} operation with a link to its page on developer.eka.care.`,
    '---',
    '',
    `<!-- ${GENERATED}. Do not edit by hand. -->`,
    '',
    `# ${branded(product.item)}`,
    '',
    `Generated from developer.eka.care. Every fact below comes from a page there, which is the place to look when this file does not carry enough. This file is a snapshot: fetch it again from ${rawSkillUrl(product.slug)} when it is older than the work you are doing.`,
    '',
    '## What you can do',
    '',
    desc || `See ${SITE}.`,
    '',
    '## Before anything else',
    '',
    `- Get an access token first. Every call needs it: ${SITE}/api-sdk/auth/getting-started`,
    '- Look an operation up on its page before you write the call. The page carries the request and response in full; this skill carries where to find it.',
    '- Do not invent an endpoint, a header or a field. Everything that exists is listed in the files below.',
    '',
    '## What is in this folder',
    '',
    ...jobs.map((j) => `- ${JOBS[j]} [references/${j}.md](references/${j}.md)`),
    '',
    'This file is the map. Open a file beside it when you need it, rather than reading them all.',
    '',
  ].join('\n');
}

function pluginJson(product, overview) {
  return JSON.stringify({
    name: `eka-${product.slug}`,
    displayName: branded(product.item),
    version: '0.1.0',
    description: `Reference skill for building against ${branded(product.item)}: hosts, auth and headers, and every operation, generated from developer.eka.care.`,
    author: { name: 'Eka Care', url: SITE },
    license: 'MIT',
    keywords: ['eka', product.slug, 'agent-skills', 'api'],
    homepage: SITE,
    repository: `https://github.com/${REPO}`,
  }, null, 2) + '\n';
}

export function build({ root = ROOT, out = ROOT, check = false } = {}) {
  const docs = JSON.parse(fs.readFileSync(path.join(root, 'docs.json'), 'utf8'));
  const specs = loadSpecs(root);
  const files = new Map();
  const ambiguous = [];
  const unresolved = [];
  const plugins = [];
  for (const product of PRODUCTS) {
    const operations = [];
    const guides = [];
    for (const page of apiPagesOf(docs, product.item)) {
      const fm = readPage(root, page);
      if (!fm) continue;
      const op = operationOf(fm, specs);
      if (op) {
        operations.push({ ...op, page, title: fm.title });
        if (op.ambiguous) ambiguous.push(`${page}: ${op.method} ${op.path} resolves to ${op.spec}`);
      } else if (fm.openapi) unresolved.push(`${page}: ${fm.openapi}`);
      else guides.push({ page, title: fm.sidebarTitle || fm.title || fm.heading || page });
    }
    if (!operations.length) continue;
    // The menu's one-line description is written for this product; its first page may be about one part of it.
    const item = findItem(docs, product.item);
    const home = docsHomeOf(docs, product.item);
    const overview = { title: product.item, description: item.description || (home && readPage(root, home)?.description) || '' };
    const dir = skillDir(product.slug);
    files.set(`plugins/eka-${product.slug}/.claude-plugin/plugin.json`, pluginJson(product, overview));
    files.set(`${dir}/SKILL.md`, skillMd(product, overview, ['integrate']));
    files.set(`${dir}/references/integrate.md`, integrateMd(product, operations, specs, guides));
    plugins.push({ name: `eka-${product.slug}`, source: `./plugins/eka-${product.slug}`,
      description: `Reference skill for ${branded(product.item)}: every operation, its hosts, auth and headers.` });
  }

  const mpFile = '.claude-plugin/marketplace.json';
  const mp = JSON.parse(fs.readFileSync(path.join(root, mpFile), 'utf8'));
  const names = new Set(plugins.map((p) => p.name));
  // Generated entries (eka-*) are rebuilt from this run; others, such as eka-docs-contributor, are kept as they are.
  const generated = (n) => n.startsWith('eka-') && n !== 'eka-docs-contributor';
  mp.plugins = [...mp.plugins.filter((p) => !names.has(p.name) && !generated(p.name)), ...plugins].sort((a, b) => (a.name < b.name ? -1 : 1));
  files.set(mpFile, JSON.stringify(mp, null, 2) + '\n');

  const changed = [];
  for (const [f, body] of files) {
    const full = path.join(out, f);
    const old = fs.existsSync(full) ? fs.readFileSync(full, 'utf8') : null;
    if (old === body) continue;
    changed.push(f);
    if (!check) {
      fs.mkdirSync(path.dirname(full), { recursive: true });
      fs.writeFileSync(full, body);
    }
  }
  // Files under a generated plugin that this run did not produce: a product that lost its operations, or a retired job
  // file. They are reported, never deleted here; removing published skills is a person's call.
  const stale = [];
  const pluginsDir = path.join(out, 'plugins');
  if (fs.existsSync(pluginsDir)) {
    for (const d of fs.readdirSync(pluginsDir)) {
      if (!d.startsWith('eka-') || d === 'eka-docs-contributor') continue;
      for (const f of fs.readdirSync(path.join(pluginsDir, d), { recursive: true })) {
        const rel = `plugins/${d}/${String(f).split(path.sep).join('/')}`;
        if (fs.statSync(path.join(out, rel)).isFile() && !files.has(rel)) stale.push(rel);
      }
    }
  }
  return { written: [...files.keys()], changed, stale: stale.sort(), ambiguous, unresolved };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const r = build({ check });
  for (const a of r.ambiguous) console.error(`ambiguous: ${a}`);
  for (const u of r.unresolved) console.error(`unresolved: ${u}`);
  if (r.stale.length) console.error(`stale (no longer generated; delete them or restore their source):\n  ${r.stale.join('\n  ')}`);
  if (check && (r.changed.length || r.stale.length)) {
    if (r.changed.length) console.error(`skills out of date (run npm run skills:build):\n  ${r.changed.join('\n  ')}`);
    process.exit(1);
  }
  console.log(`${r.written.length} files, ${r.changed.length} ${check ? 'would change' : 'written'}`);
}
