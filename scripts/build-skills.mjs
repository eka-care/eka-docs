// Builds one reference skill per product from its API pages, the way the ABDM portal builds its module skills.
//
// A product's "APIs & SDKs" tab in docs.json is already the list of its operations: each reference page names its
// operation in an `openapi:` line. This script resolves every line to its spec and writes, per product:
//
//   plugins/eka-<slug>/.claude-plugin/plugin.json
//   plugins/eka-<slug>/skills/eka-<slug>/SKILL.md               the map, with the rules to know first
//   plugins/eka-<slug>/skills/eka-<slug>/references/integrate.md hosts, auth and headers, every operation, one request
//
// Scaffold, debug and test files come later, when a product has workflow pages, recorded errors and a test matrix.
// A job file that does not exist is not listed. Everything here is generated: edit the specs and pages, not the skill.
//
// Run: node scripts/build-skills.mjs            write the files
//      node scripts/build-skills.mjs --check    exit 1 if any file would change

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import matter from 'gray-matter';
import YAML from 'yaml';
import { normalizeOp } from './docs-check.mjs';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://developer.eka.care';
const REPO = 'eka-care/eka-docs';
const RAW = `https://raw.githubusercontent.com/${REPO}/main`;
const GENERATED = 'generated by scripts/build-skills.mjs';
const API_TAB = 'APIs & SDKs';
const METHODS = ['get', 'put', 'post', 'delete', 'patch', 'head', 'options'];
const SKIP_DIRS = new Set(['node_modules', '.git', '.superpowers', '.claude', 'plugins', 'superpowers']);

// ABDM Connect has its own plugin (abdm-connect, eka-abdm marketplace), so it gets no generated one here.
